#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="${PROJECT_DIR:-$(cd "$SCRIPT_DIR/.." && pwd)}"
DRY_ROOT="${DRY_ROOT:-$PROJECT_DIR/dryrun}"

# Smoke profile: one rep per task/mode (6 runs total)
N_REPS="${N_REPS:-1}"
TASKS_CSV="${TASKS_CSV:-JWT,IDOR,BIZ}"
MAX_TURNS="${MAX_TURNS:-35}"
COOLDOWN_SECONDS="${COOLDOWN_SECONDS:-5}"
STRICT_MODE="${STRICT_MODE:-1}"
STRICT_SCREENSHOT="${STRICT_SCREENSHOT:-1}"
MCP_HEADLESS="${MCP_HEADLESS:-1}"

mkdir -p "$DRY_ROOT"

OUTPUT_ROOT="$DRY_ROOT" \
N_REPS="$N_REPS" \
TASKS_CSV="$TASKS_CSV" \
MAX_TURNS="$MAX_TURNS" \
COOLDOWN_SECONDS="$COOLDOWN_SECONDS" \
STRICT_MODE="$STRICT_MODE" \
STRICT_SCREENSHOT="$STRICT_SCREENSHOT" \
MCP_HEADLESS="$MCP_HEADLESS" \
"$SCRIPT_DIR/run_experiment.sh"
